"""Renders the final, human-readable Markdown report: summary counts, a
by-venue and by-topic breakdown, then the full paper listing -- including
abstracts -- grouped by venue, so a reviewer can screen the whole pool
without opening a browser tab per paper."""
import os
from collections import defaultdict


def _year(published):
    return (published or "")[:4] or "n.d."


def _paper_entry(c):
    lines = []
    title = c.get("title") or "(untitled)"
    lines.append(f"### {title} ({_year(c.get('published'))})")

    meta = []
    if c.get("_venue"):
        meta.append(f"**Venue:** {c['_venue']}")
    elif c.get("_raw_venue"):
        meta.append(f"**Venue (unconfirmed):** {c['_raw_venue']}")
    authors = [a for a in (c.get("authors") or []) if a]
    if authors:
        meta.append(f"**Authors:** {', '.join(authors)}")
    if c.get("arxiv_id"):
        meta.append(f"[arXiv:{c['arxiv_id']}](https://arxiv.org/abs/{c['arxiv_id']})")
    if c.get("s2_paper_id"):
        meta.append(f"[Semantic Scholar](https://www.semanticscholar.org/paper/{c['s2_paper_id']})")
    if c.get("pdf_url"):
        meta.append(f"[PDF]({c['pdf_url']})")
    if meta:
        lines.append(" · ".join(meta))

    if c.get("_topics"):
        lines.append(f"**Matched topics:** {', '.join(c['_topics'])}")
    if c.get("_already_known"):
        lines.append("_Already in your known-titles list._")

    lines.append("")
    lines.append(c.get("summary") or "_No abstract available._")
    lines.append("")
    return "\n".join(lines)


def write_report(config, in_scope, excluded, venue_matcher, s2_authenticated):
    os.makedirs(config.output_dir, exist_ok=True)
    path = os.path.join(config.output_dir, "report.md")

    by_venue = defaultdict(list)
    for c in in_scope.values():
        by_venue[c.get("_venue") or "(no venue restriction)"].append(c)

    by_topic = defaultdict(list)
    for c in in_scope.values():
        for t in (c.get("_topics") or ["(untagged)"]):
            by_topic[t].append(c)

    lines = [f"# {config.project_name}", ""]

    mode_note = (
        "Full pipeline: arXiv + Semantic Scholar + DBLP, with citation-graph snowballing."
        if s2_authenticated else
        "arXiv + DBLP only -- no Semantic Scholar API key was found, so topic search on "
        "Semantic Scholar, citation snowballing, and batch venue re-confirmation were "
        "skipped. See README.md to add a key."
    )
    lines.append(f"Generated by [papelito](https://github.com/QwertyJacob/papelito). {mode_note}")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Topics searched: {len(config.topics)}")
    lines.append(
        "- Venue allow-list: "
        + ("none (all venues kept)" if venue_matcher.is_empty else ", ".join(v.name for v in config.venues))
    )
    lines.append(f"- Papers in scope: **{len(in_scope)}**")
    lines.append(f"- Papers found but excluded (no confirmed allow-listed venue): {len(excluded)}")
    if config.known_titles_file:
        already_known = sum(1 for c in in_scope.values() if c.get("_already_known"))
        lines.append(f"- Of which already in your known-titles list: {already_known}")
    lines.append("")

    lines.append("## By venue")
    lines.append("")
    for venue in sorted(by_venue, key=lambda v: -len(by_venue[v])):
        lines.append(f"- **{venue}**: {len(by_venue[venue])}")
    lines.append("")

    lines.append("## By topic")
    lines.append("")
    for topic in sorted(by_topic, key=lambda t: -len(by_topic[t])):
        lines.append(f"- **{topic}**: {len(by_topic[topic])}")
    lines.append("")

    lines.append("## Papers")
    lines.append("")
    for venue in sorted(by_venue, key=lambda v: (-len(by_venue[v]), v)):
        lines.append(f"## {venue}")
        lines.append("")
        for c in sorted(by_venue[venue], key=lambda c: c.get("title") or ""):
            lines.append(_paper_entry(c))

    if excluded:
        lines.append("---")
        lines.append("")
        lines.append("## Found but excluded (no confirmed allow-listed venue)")
        lines.append("")
        lines.append(
            "Kept here for transparency -- these matched a topic query but did not "
            "confirm a venue on the allow-list through any source checked."
        )
        lines.append("")
        for c in sorted(excluded.values(), key=lambda c: c.get("title") or ""):
            lines.append(_paper_entry(c))

    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path
